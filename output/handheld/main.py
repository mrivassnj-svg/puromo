import asyncio
import logging
import time
import sys

# Configure logging BEFORE any imports that use it
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s — %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("main")

# ─── Boot Phase 0: Power rail settle ─────────────────────────────
logger.info("[BOOT 0] Power rail settle — waiting 50ms")
time.sleep(0.050)

# ─── Boot Phase 1: GPIO direction setup ──────────────────────────
logger.info("[BOOT 1] GPIO direction setup")
import RPi.GPIO as GPIO
GPIO.setwarnings(False)
GPIO.setmode(GPIO.BCM)

# ─── Boot Phase 2: Bus init ───────────────────────────────────────
logger.info("[BOOT 2] SPI + I2C bus init")
# SPI and I2C are opened lazily by each driver

# ─── Boot Phase 3+4: Display hardware reset + init ───────────────
logger.info("[BOOT 3+4] Display hardware reset and init")
from drivers.display_st7789 import display
try:
    display.init()
except Exception as e:
    logger.critical(f"[BOOT] Display init FAILED: {e}")
    sys.exit(1)

# ─── Boot Phase 5: Backlight on ──────────────────────────────────
logger.info("[BOOT 5] Backlight on")
from drivers.backlight import backlight
backlight.init()

# ─── Boot Phase 6: Input init ────────────────────────────────────
logger.info("[BOOT 6] Input (buttons + joystick) init")
from drivers.buttons  import buttons
from drivers.joystick import joystick
buttons.init()
joystick.init()

# ─── Boot Phase 7: Secondary peripherals ─────────────────────────
logger.info("[BOOT 7] Secondary peripherals")
from drivers.imu_mpu6050 import imu
from drivers.audio       import audio
from drivers.battery     import battery_monitor

for name, driver in [("IMU", imu), ("Audio", audio)]:
    try:
        driver.init()
    except Exception as e:
        logger.warning(f"[BOOT 7] {name} not found or init failed: {e} (skipping)")

# ─── Boot Phase 8: Battery monitor start ─────────────────────────
logger.info("[BOOT 8] Battery monitor")
battery_monitor.init()

# ─── Boot Phase 9: EventBus + application ─────────────────────────
logger.info("[BOOT 9] EventBus + application")
from event_bus import bus
from app.app   import HandheldApp

app = HandheldApp()

# ─── Boot Phase 10: Show splash then start ───────────────────────
logger.info("[BOOT 10] Application start")
# Fade backlight in over 400ms
# asyncio.run() will handle the rest
display.fill(display.rgb(0, 0, 32))   # dark blue splash


async def main_loop():
    # Start all async tasks concurrently
    async with asyncio.TaskGroup() as tg:
        # Backlight fade-in
        tg.create_task(backlight.fade_in())
        # Input polling
        tg.create_task(joystick.run())
        # Battery monitoring
        tg.create_task(battery_monitor.run())
        # IMU sampling
        tg.create_task(imu.run())
        # EventBus queue drainer (flushes IRQ-posted events)
        async def drain_loop():
            while True:
                await bus.drain()
                await asyncio.sleep(0.001)
        tg.create_task(drain_loop())
        # Main application
        tg.create_task(app.run())


try:
    asyncio.run(main_loop())
except KeyboardInterrupt:
    logger.info("[SHUTDOWN] KeyboardInterrupt — cleaning up")
finally:
    backlight.off()
    display.close()
    joystick.close()
    buttons.close()
    battery_monitor.stop()
    GPIO.cleanup()
    logger.info("[SHUTDOWN] Clean exit")

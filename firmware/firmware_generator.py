class FirmwareGenerator:
    """
    Orchestrates all template generators and writes the full firmware tree.
    """

    def __init__(self, spec: dict, output_root: str = "output"):
        self.spec = spec
        model = spec.get("model", "handheld").replace(" ", "_").lower()
        self.out = Path(output_root) / model
        self.load_order = topo_sort(DRIVER_DEPS)

    def generate(self) -> dict:
        """Generate all firmware files and return manifest."""
        (self.out / "drivers").mkdir(parents=True, exist_ok=True)
        (self.out / "app").mkdir(parents=True, exist_ok=True)

        files = {}
        files["config.py"]             = self._write("config.py",             TEMPLATES["config"](self.spec))
        files["event_bus.py"]          = self._write("event_bus.py",           TEMPLATES["event_bus"](self.spec))
        files["drivers/display_st7789.py"] = self._write("drivers/display_st7789.py", TEMPLATES["display_st7789"](self.spec))
        files["drivers/backlight.py"]  = self._write("drivers/backlight.py",   TEMPLATES["backlight"](self.spec))
        files["drivers/buttons.py"]    = self._write("drivers/buttons.py",     TEMPLATES["buttons"](self.spec))
        files["drivers/joystick.py"]   = self._write("drivers/joystick.py",    TEMPLATES["joystick"](self.spec))
        files["drivers/battery.py"]    = self._write("drivers/battery.py",     TEMPLATES["battery"](self.spec))
        files["drivers/imu_mpu6050.py"]= self._write("drivers/imu_mpu6050.py", TEMPLATES["imu_mpu6050"](self.spec))
        files["drivers/audio.py"]      = self._write("drivers/audio.py",       TEMPLATES["audio"](self.spec))
        files["app/state_machine.py"]  = self._write("app/state_machine.py",   TEMPLATES["state_machine"](self.spec))
        files["app/app.py"]            = self._write("app/app.py",             TEMPLATES["app"](self.spec))
        files["app/__init__.py"]       = self._write("app/__init__.py",        "")
        files["drivers/__init__.py"]   = self._write("drivers/__init__.py",    "")
        files["main.py"]               = self._write("main.py",                TEMPLATES["main"](self.spec))
        files["README_FIRMWARE.md"]    = self._write("README_FIRMWARE.md",     TEMPLATES["readme"](self.spec))

        manifest = {
            "model":       self.spec.get("model"),
            "output_dir":  str(self.out),
            "files":       {k: str(self.out/k) for k in files},
            "boot_phases": BOOT_PHASES,
            "driver_load_order": self.load_order,
            "scheduler":   SCHEDULER_DESIGN,
            "event_types": EVENT_TYPES,
        }
        self._write("firmware_manifest.json", json.dumps(manifest, indent=2))
        return manifest

    def _write(self, relpath: str, content: str) -> str:
        path = self.out / relpath
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        return str(path)

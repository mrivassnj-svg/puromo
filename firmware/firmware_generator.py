# ---------------------------------------------------------------------------
# Topological sort for driver load order
# ---------------------------------------------------------------------------
def topo_sort(deps: Dict[str, List[str]]) -> List[str]:
    visited, order = set(), []
    def visit(node):
        if node in visited: return
        visited.add(node)
        for dep in deps.get(node, []):
            visit(dep)
        order.append(node)
    for n in deps:
        visit(n)
    return order


# ---------------------------------------------------------------------------
# Template registry — maps driver_key → generator function
# ---------------------------------------------------------------------------
TEMPLATES: Dict[str, callable] = {}

